import test from 'node:test';
import assert from 'node:assert/strict';
import { harness, response, usage, analytics, endpoint } from './helpers.js';

test('countdown: compact relative reset text changes only on existing show/poll renders, preserves exact dates and summary, and marks due without restoring quota', async () => {
  const base = new Date(2026, 9, 27, 20, 0).getTime();
  const body = structuredClone(usage);
  body.rate_limit.primary_window.reset_at = (base + 2 * 3600000) / 1000;
  body.rate_limit.secondary_window.reset_at = (base + 3600000) / 1000;
  body.code_review_rate_limit = { primary_window: { used_percent: 12, limit_window_seconds: 604800, reset_at: base / 1000 } };
  body.additional_rate_limits = [{ limit_name: 'Daily extra', rate_limit: { primary_window: { used_percent: 20, limit_window_seconds: 86400, reset_at: null } } }];
  const options = { now: base, fetch: url => response(String(url) === endpoint ? body : analytics) };
  const h = await harness(options);
  await h.fire('session_start');
  await h.command();
  const rows = h.compactText().split('\n');
  const primary = rows.find(row => /Limit: 7 days/.test(row));
  assert.match(primary, /Reset 2026\.10\.27 22:00/, 'Exact host-local reset date stays visible');
  assert.match(primary, /\b2\s*h(?:ours?)?\b/i, 'Future quota shows a human remaining duration beside the date');
  assert.match(rows.find(row => /Limit: 5 hours/.test(row)), /\b1\s*h(?:ours?)?\b/i);
  assert.match(rows.find(row => /Code review limits/.test(row)), /Reset due/i, 'Equality with now is already due');
  assert.doesNotMatch(rows.find(row => /Daily extra/.test(row)), /Reset|due|remaining|unknown|unavailable/i, 'Missing reset date has no countdown placeholder');
  assert.equal(h.statuses.at(-1).text, 'Codex usage · 75% left');
  assert.match(h.compactText(), /Updated: 2026\.10\.27 20:00/);
  assert.equal(h.timers.size, 1);
  assert.deepEqual([...h.timers.values()].map(timer => timer.ms), [180000], 'No compact minute timer can resurrect a host-dismissed dock');
  const writes = h.widgets.length;
  const before = h.requests.length;
  options.now = base + 3 * 3600000;
  assert.equal(h.widgets.length, writes, 'Clock movement alone never rewrites compact text');
  assert.equal(h.requests.length, before);
  await [...h.timers.values()][0].callback();
  assert.equal(h.requests.length, before + 2, 'Existing poll still fetches only its two original sources');
  const after = h.compactText().split('\n').find(row => /Limit: 7 days/.test(row));
  assert.match(after, /Reset 2026\.10\.27 22:00/);
  assert.match(after, /Reset due/i);
  assert.match(after, /25%/, 'Due time does not imply restored quota');
  assert.equal(h.statuses.at(-1).text, 'Codex usage · 75% left');
});
